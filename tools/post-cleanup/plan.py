def theme_of(text):
    t=re.sub(r"#\S*","",text)
    best=None;bs=0
    for k,(pat,_) in THEMES.items():
        n=len(re.findall(pat,t))
        if n>bs: best,bs=k,n
    return best or "general"
def tags_for(text,theme,n=6):
    t=re.sub(r"#\S*","",text)
    sel=[]
    order=[theme]+[k for k,v in sorted(THEMES.items(),key=lambda kv:-len(re.findall(kv[1][0],t))) if k!=theme and re.search(v[0],t)]
    for k in order:
        if k=="general": continue
        for tg in THEMES[k][1]:
            if tg not in sel: sel.append(tg)
            if len(sel)>=n-1: break
        if len(sel)>=n-1: break
    if not sel: sel=GENERAL_TAGS[:n-1]
    sel=sel[:n-1]+["#SiriStudioPhoto"]
    return sel


def extract_old(fl):
    hits=[]
    for k,(pat,rep) in G.items():
        for m in re.finditer(pat,fl):
            hits.append((m.start(),m.end(),k,m.group(0),rep))
    hits.sort()
    sel=[];end=-1
    for h in hits:
        if h[0]>=end: sel.append(h); end=h[1]
    return sel


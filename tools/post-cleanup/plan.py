def finalize(res,posts,need_media,cap=10):
    """cap near-identical bodies; prefer posts whose images need no repair, then newer posts"""
    groups=collections.defaultdict(list)
    for r in res:
        if r["active"] and r["tier"].startswith("B-"): groups[(r["theme"],r["tier"])].append(r)
    for k,l in groups.items():
        def key(r):
            p=posts[r["idx"]]
            bad=sum(1 for m in p["media_ids"] if m in need_media)
            return (bad>0,-len(p["media_ids"])>-1 and 0,p["created_at"][::-1])  # clean images first
        l.sort(key=lambda r:(sum(1 for m in posts[r["idx"]]["media_ids"] if m in need_media)>0, [-ord(c) for c in posts[r["idx"]]["created_at"]]))
        for r in l[cap:]:
            r["active"]=False; r["tier"]="reject"; r["code"]="dup"; r["reason"]="ข้อความซ้ำกับโพสต์อื่นที่คัดไว้แล้ว (จำกัดไม่เกิน %d โพสต์ต่อข้อความเดียวกัน เพื่อไม่ให้โพสต์ซ้ำในกลุ่มเดิม ๆ)"%cap
    return res
